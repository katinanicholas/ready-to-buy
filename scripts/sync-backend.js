// Copies the canonical assessment logic into the Apps Script project.
// Run after ANY edit to docs/js/assessment.js:  npm run sync
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = path.join(root, 'docs/js/assessment.js');
const dest = path.join(root, 'backend/apps-script/Assessment.gs');
const banner = '// GENERATED by scripts/sync-backend.js from docs/js/assessment.js. DO NOT EDIT.\n';
fs.writeFileSync(dest, banner + fs.readFileSync(src, 'utf8'));
console.log('Synced', path.relative(root, src), '->', path.relative(root, dest));
